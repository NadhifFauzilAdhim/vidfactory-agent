/**
 * A scene whose visuals were written as code (HTML + CSS + GSAP) instead of generated as an image.
 *
 * "code" scenes run inside an iframe so authored CSS cannot leak into the template chrome and
 * authored JS cannot touch Remotion's React tree.
 *
 * Two constraints shaped this component, both found by rendering rather than reasoning about it:
 *
 * 1. `contentDocument.write()` is never captured by Remotion's screenshot path, while a document
 *    loaded from a URL is. The scene is therefore served from a `blob:` URL built from the scene's
 *    shell, rebuilt only when the code changes.
 * 2. `postMessage` is delivered on a LATER task, while Remotion screenshots right after React
 *    commits. Seeking that way always rendered frame 0 — every scene looked frozen no matter what
 *    GSAP did. A blob URL is same-origin, so `__seek()` can be called synchronously inside
 *    `useLayoutEffect` and the frame is correct before the screenshot.
 *
 * `sandbox="allow-scripts"` is kept, but `allow-same-origin` must accompany it for the blob URL to be
 * scriptable from the parent. That is safe here because the document is generated by us and lives in
 * the same render process; the scene still cannot reach the network or another window.
 */

import type React from "react";
import {useEffect, useLayoutEffect, useMemo, useRef, useState} from "react";
import {AbsoluteFill, staticFile, useCurrentFrame, useVideoConfig} from "remotion";

import {buildShell, stripDocumentWrapper} from "./code-runtime";
import type {SceneCode} from "./types";

/**
 * Inline GSAP build, staged into the public dir by `render.mjs` and copied for the Studio.
 *
 * It must be fetched with `staticFile()` and not as `/vendor/...`: inside a render, Remotion serves
 * the bundle from a nested path, so an absolute root URL 404s and every scene silently runs without
 * GSAP.
 */
export const GSAP_SRC = "vendor/gsap.min.js";

type SceneWindow = Window & {
  __seek?: (frame: number, fps: number) => void;
  __ready?: boolean;
  __codeErrors?: string[];
};

export const CodeScene: React.FC<{code: SceneCode; accent?: string}> = ({code, accent}) => {
  const frame = useCurrentFrame();
  const {fps} = useVideoConfig();
  const ref = useRef<HTMLIFrameElement>(null);
  const [gsapSource, setGsapSource] = useState<string | null>(null);
  const [documentUrl, setDocumentUrl] = useState<string | null>(null);

  useEffect(() => {
    let alive = true;
    let cached = gsapCache;
    if (cached === undefined) {
      cached = fetch(staticFile(GSAP_SRC))
        .then((res) => (res.ok ? res.text() : null))
        .catch(() => null);
      gsapCache = cached;
    }
    cached.then((source) => {
      if (alive) setGsapSource(source);
    });
    return () => {
      alive = false;
    };
  }, []);

  // One document per distinct scene program. A blob URL is same-origin, which is what makes the
  // synchronous seek below possible.
  const shellHtml = useMemo(
    () =>
      buildShell({
        html: stripDocumentWrapper(code.html),
        css: code.css,
        js: code.js,
        gsapSource,
        accent,
      }),
    [code.html, code.css, code.js, gsapSource, accent],
  );

  // Rebuild the blob only when the program changes, never per frame. The first render has no GSAP
  // source yet; rebuilding once it arrives is intended, and the effect below tolerates it.
  useLayoutEffect(() => {
    const url = URL.createObjectURL(new Blob([shellHtml], {type: "text/html"}));
    setDocumentUrl((previous) => {
      if (previous) {
        setTimeout(() => URL.revokeObjectURL(previous), 1000);
      }
      return url;
    });
  }, [shellHtml]);

  // The frame is delivered by message because the document is sandboxed. Remotion wraps
  // `remotion_setFrame` in `delayRender()` and only continues after a requestAnimationFrame, so a
  // message posted here is processed before the screenshot is taken — but only if the frame is
  // posted on EVERY render, which is why this effect depends on `frame` alone and not on the URL.
  useLayoutEffect(() => {
    const win = ref.current?.contentWindow as SceneWindow | null;
    win?.__seek?.(frame, fps);
    win?.postMessage?.({type: "factory:seek", frame, fps}, "*");
  }, [documentUrl, frame, fps]);

  return (
    <AbsoluteFill>
      {documentUrl ? (
        <iframe
          ref={ref}
          title="code-scene"
          src={documentUrl}
          sandbox="allow-scripts allow-same-origin"
          scrolling="no"
          style={{
            border: "none",
            width: "100%",
            height: "100%",
            display: "block",
            background: "transparent",
          }}
        />
      ) : null}
    </AbsoluteFill>
  );
};

let gsapCache: Promise<string | null> | undefined;
